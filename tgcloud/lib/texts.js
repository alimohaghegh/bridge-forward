export function statusText(user) {
  if (!user || !user.baleChatId) {
    return '🔌 حساب بله شما هنوز متصل نیست.\nبرای اتصال، /link را بزنید.';
  }
  return [
    '✅ حساب بله شما متصل است.',
    `📅 تاریخ اتصال: ${formatDate(user.linkedAt)}`,
    `📨 پیام‌های رسیده: ${user.deliveredCount}`,
    `⚠️ پیام‌های ناموفق: ${user.failedCount}`,
    '',
    'برای قطع اتصال /unlink و برای آزمایش /test را بزنید.',
  ].join('\n');
}
